def build_designspace(
    family_dir: Path,
    ufo_paths: dict[str, Path],  # weight_name -> UFO path
    metrics: dict,
    dry_run: bool = False,
) -> Path:
    """
    Generate a DesignSpace file at ``<family_dir>/<FamilyName>.designspace``.
    For a single master (no variable), creates a minimal static-axis DS.
    For multiple masters keyed by weight value, creates a wght axis.
    """
    family_raw  = metrics.get("family_name", family_dir.name)
    family_name = family_raw.replace("OctalFont-", "OctalFont ")
    ds_path     = family_dir / f"{family_dir.name}.designspace"

    if dry_run:
        print(f"  DesignSpace would be written -> {ds_path.relative_to(family_dir.parent.parent)}")
        return ds_path

    doc = DesignSpaceDocument()

    weight_map: dict[str, int] = {
        "Thin":       100,
        "ExtraLight": 200,
        "Light":      300,
        "Regular":    400,
        "Medium":     500,
        "SemiBold":   600,
        "Bold":       700,
        "ExtraBold":  800,
        "Black":      900,
    }

    if len(ufo_paths) > 1:
        # Variable: add wght axis
        axis = AxisDescriptor()
        axis.tag      = "wght"
        axis.name     = "Weight"
        axis.minimum  = min(weight_map.get(w, 400) for w in ufo_paths)
        axis.default  = weight_map.get("Regular", 400)
        axis.maximum  = max(weight_map.get(w, 400) for w in ufo_paths)
        doc.addAxis(axis)
    else:
        # Static: add a dummy wght axis so fontmake is happy
        axis = AxisDescriptor()
        axis.tag     = "wght"
        axis.name    = "Weight"
        axis.minimum = axis.default = axis.maximum = 400
        doc.addAxis(axis)

    for weight_name, ufo_path in ufo_paths.items():
        src = SourceDescriptor()
        src.filename   = str(ufo_path.relative_to(family_dir))
        src.familyName = family_name
        src.styleName  = weight_name
        src.location   = {"Weight": weight_map.get(weight_name, 400)}
        src.copyInfo   = weight_name == "Regular" or len(ufo_paths) == 1
        doc.addSource(src)

        # Add a matching instance so gftools builder can generate static TTFs
        inst = InstanceDescriptor()
        inst.familyName = family_name
        inst.styleName  = weight_name
        inst.name       = f"{family_name} {weight_name}"
        inst.location   = {"Weight": weight_map.get(weight_name, 400)}
        inst.filename   = f"instances/{family_name.replace(' ', '')}-{weight_name}.ufo"
        doc.addInstance(inst)

    doc.write(str(ds_path))
    print(f"  DesignSpace written -> {ds_path.relative_to(family_dir.parent.parent)}")
    return ds_path


