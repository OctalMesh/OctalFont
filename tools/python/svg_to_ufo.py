def _load_metrics(family_dir: Path) -> dict:
    metrics_file = family_dir / "metrics.yaml"
    if not metrics_file.exists():
        print(f"  [INFO] metrics.yaml not found, using defaults.")
        return {}
    with metrics_file.open() as fh:
        return yaml.safe_load(fh) or {}


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Convert per-glyph SVG files into a UFO master + DesignSpace.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "family_dir",
        type=Path,
        help="Path to the family source directory (e.g. sources/OctalFont-Titan)",
    )
    parser.add_argument(
        "--weight",
        default="Regular",
        help="Weight name for the UFO master (default: Regular)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print what would be done without writing any files",
    )
    args = parser.parse_args(argv)

    family_dir: Path = args.family_dir.resolve()
    if not family_dir.is_dir():
        print(f"[ERROR] Family directory not found: {family_dir}", file=sys.stderr)
        return 1

    print(f"\n[svg_to_ufo] Family: {family_dir.name}")
    print(f"  Weight:  {args.weight}")
    if args.dry_run:
        print("  Mode:    DRY RUN (no files will be written)\n")

    metrics = _load_metrics(family_dir)
    metrics.setdefault("family_name", family_dir.name)

    try:
        ufo_path = build_ufo(
            family_dir=family_dir,
            weight_name=args.weight,
            metrics=metrics,
            dry_run=args.dry_run,
        )
        build_designspace(
            family_dir=family_dir,
            ufo_paths={args.weight: ufo_path},
            metrics=metrics,
            dry_run=args.dry_run,
        )
    except FileNotFoundError as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        return 1
    except Exception as exc:
        import traceback
        print(f"[ERROR] Unexpected error: {exc}", file=sys.stderr)
        traceback.print_exc()
        return 1

    if not args.dry_run:
        print("\n[svg_to_ufo] Done.\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
