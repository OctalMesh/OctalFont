def build_ufo(
    family_dir: Path,
    weight_name: str,
    metrics: dict,
    dry_run: bool = False,
) -> Path:
    """
    Create a UFO master at
    ``<family_dir>/ufo/<weight_name>.ufo``
    from all SVG files found under ``<family_dir>/svg/``.
    Returns the UFO path.
    """
    svg_root = family_dir / "svg"
    ufo_path = family_dir / "ufo" / f"{weight_name}.ufo"

    # Metrics
    upm        = int(metrics.get("upm",        1000))
    ascender   = int(metrics.get("ascender",    800))
    descender  = int(metrics.get("descender",  -200))
    cap_height = int(metrics.get("cap_height",  700))
    x_height   = int(metrics.get("x_height",   500))
    svg_ref    = float(metrics.get("svg_ref_size", 1000))
    family_raw = metrics.get("family_name", family_dir.name)
    # Remove weight suffix from the style-less family name
    family_name = family_raw.replace("OctalFont-", "OctalFont ")

    transform = _Transform(cap_height=cap_height, svg_ref=svg_ref)

    # Collect SVG files
    svg_files: list[Path] = sorted(svg_root.rglob("*.svg"))
    if not svg_files:
        raise FileNotFoundError(f"No SVG files found under {svg_root}")

    print(f"  Found {len(svg_files)} SVG file(s) under {svg_root}")

    if dry_run:
        for f in svg_files:
            stem = f.stem
            gname, cp = _stem_to_glyph(stem)
            uni = f" U+{cp:04X}" if cp else " (no unicode)"
            print(f"    {f.relative_to(family_dir)}  ->  {gname}{uni}")
        return ufo_path

    # Build UFO
    ufo = ufoLib2.Font()

    # Basic font info
    ufo.info.familyName = family_name
    ufo.info.styleName  = weight_name
    ufo.info.unitsPerEm = upm
    ufo.info.capHeight  = cap_height
    ufo.info.xHeight    = x_height
    ufo.info.postscriptUnderlinePosition  = int(metrics.get("underline_position",  -100))
    ufo.info.postscriptUnderlineThickness = int(metrics.get("underline_thickness",   50))

    # Version
    version_str = str(metrics.get("version", "1.000"))
    try:
        major_str, minor_str = version_str.split(".", 1)
        ufo.info.versionMajor = int(major_str)
        ufo.info.versionMinor = int(minor_str)
    except ValueError:
        ufo.info.versionMajor, ufo.info.versionMinor = 1, 0

    # Identity / legal name records
    ufo.info.copyright                   = metrics.get("copyright", "")
    ufo.info.openTypeNameDesigner        = metrics.get("designer", "")
    ufo.info.openTypeNameDesignerURL     = metrics.get("designer_url", "")
    ufo.info.openTypeNameManufacturer    = metrics.get("manufacturer", "")
    ufo.info.openTypeNameManufacturerURL = metrics.get("manufacturer_url", "")
    ufo.info.openTypeNameLicense         = metrics.get("license", "")
    ufo.info.openTypeNameLicenseURL      = metrics.get("license_url", "")
    ufo.info.openTypeOS2VendorID         = str(metrics.get("vendor_id", "NONE"))[:4].upper()

    # Embedding / licensing
    # fsType = 0  ->  Installable Embedding (required for OFL / MIT fonts).
    # An empty list encodes the value 0 in ufoLib2.
    ufo.info.openTypeOS2Type = []

    # Vertical metrics
    # sTypo / hhea = line-box ascender/descender from metrics.yaml.
    # Google Fonts requires: hhea.ascender + |hhea.descender| + lineGap >= 1200.
    # USE_TYPO_METRICS (fsSelection bit 7, set by fix_production.py) tells
    # renderers to use sTypo* for line spacing rather than Win values.
    ufo.info.openTypeOS2TypoAscender  = ascender
    ufo.info.openTypeOS2TypoDescender = descender
    ufo.info.openTypeOS2TypoLineGap   = 0
    ufo.info.openTypeHheaAscender     = ascender
    ufo.info.openTypeHheaDescender    = descender
    ufo.info.openTypeHheaLineGap      = 0
    # Win values = actual glyph bounding-box ceiling/floor.
    # Set to cap_height/0 here; fix_production.py recomputes from compiled glyphs.
    ufo.info.openTypeOS2WinAscent     = cap_height
    ufo.info.openTypeOS2WinDescent    = 0
    # Expose ascender/descender also for PS/legacy consumers
    ufo.info.ascender  = ascender
    ufo.info.descender = descender

    # Add a .notdef glyph
    notdef = ufo.newGlyph(".notdef")
    notdef.width = round(cap_height * 0.6)
    pen = notdef.getPointPen()
    pen.beginPath()
    w = notdef.width
    h = cap_height
    m = round(w * 0.1)  # margin
    t = round(w * 0.08) # stroke thickness
    pen.addPoint((m, 0), segmentType="line")
    pen.addPoint((w - m, 0), segmentType="line")
    pen.addPoint((w - m, h), segmentType="line")
    pen.addPoint((m, h), segmentType="line")
    pen.endPath()
    # Inner rectangle (counter)
    pen.beginPath()
    pen.addPoint((m + t, t), segmentType="line")
    pen.addPoint((m + t, h - t), segmentType="line")
    pen.addPoint((w - m - t, h - t), segmentType="line")
    pen.addPoint((w - m - t, t), segmentType="line")
    pen.endPath()

    # Process SVG files
    skipped = 0
    imported = 0
    for svg_file in svg_files:
        stem = svg_file.stem
        gname, cp = _stem_to_glyph(stem)

        try:
            glyph = ufo.newGlyph(gname)
            if cp is not None:
                glyph.unicodes = [cp]

            _svg_to_glyph(svg_file, glyph, transform)
            imported += 1
            uni_str = f"U+{cp:04X}" if cp else "no-uni"
            print(f"    [{uni_str}]  {gname:20s}  ← {svg_file.relative_to(family_dir)}")

        except Exception as exc:
            print(f"  [WARN] Skipping {svg_file.name}: {exc}", file=sys.stderr)
            skipped += 1

    print(f"  Imported: {imported}  |  Skipped: {skipped}")

    # Add a basic space glyph if not provided by SVGs
    if "space" not in ufo:
        sp = ufo.newGlyph("space")
        sp.unicodes = [0x0020]
        sp.width    = round(cap_height * 0.3)
    # U+00A0 NO-BREAK SPACE - required by fontbakery whitespace_glyphs check.
    # Identical to regular space (same advance, no contours).
    if "nbspace" not in ufo:
        nbsp = ufo.newGlyph("nbspace")
        nbsp.unicodes = [0x00A0]
        nbsp.width    = ufo["space"].width
    # Preserve existing hand-edited features.fea; only write the stub on first run.
    # ufo.features.text is always empty for a freshly created Font() object,
    # so we must check the file on disk rather than the in-memory attribute.
    features_path = ufo_path / "features.fea"
    if features_path.exists():
        ufo.features.text = features_path.read_text(encoding="utf-8")
    else:
        ufo.features.text = _FEATURES_STUB.replace("{family_name}", family_name)
    # Save
    ufo_path.parent.mkdir(parents=True, exist_ok=True)
    ufo.save(str(ufo_path), overwrite=True)
    print(f"  UFO written -> {ufo_path.relative_to(family_dir.parent.parent)}")
    return ufo_path


