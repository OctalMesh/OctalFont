def _stem_to_glyph(stem: str) -> tuple[str, Optional[int]]:
    """Return (glyph_name, unicode_or_None) for an SVG filename stem."""
    if stem in _FILENAME_MAP:
        return _FILENAME_MAP[stem]

    # Single printable ASCII character (A-Z, a-z, etc.)
    if len(stem) == 1 and stem.isprintable():
        cp = ord(stem)
        # Derive AGLFN-compatible name from Unicode character name
        try:
            uname = unicodedata.name(stem).lower().replace(" ", "")
        except ValueError:
            uname = stem
        # For plain letters just use the letter itself as name
        if stem.isalpha():
            return stem, cp
        return uname, cp

    # Unknown / ligature / etc. -> no unicode assignment
    return stem, None


# ---------------------------------------------------------------------------
# SVG path parser
# ---------------------------------------------------------------------------
# Tokenises the `d` attribute and drives a ufoLib2 PointPen.
# Supports: M m L l H h V v C c S s Q q T t A a Z z
# For arc commands (A/a) a cubic-bezier approximation is used.
# ---------------------------------------------------------------------------

_PATH_TOKEN = re.compile(
    r"([MmLlHhVvCcSsQqTtAaZz])|([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)"
)


def _tokenize(d: str) -> Iterator[str]:
    for m in _PATH_TOKEN.finditer(d):
        yield m.group(0)


def _numbers(tokens: Iterator[str], n: int) -> List[float]:
    result: List[float] = []
    while len(result) < n:
        t = next(tokens)
        if t.lstrip("+-").replace(".", "", 1).replace("e", "", 1).replace("E", "", 1).replace("+", "", 1).replace("-", "", 1).isdigit() or re.fullmatch(r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?", t):
            result.append(float(t))
    return result


def _arc_to_cubics(
    x1: float, y1: float,
    rx: float, ry: float,
    phi_deg: float,
    large_arc: int, sweep: int,
    x2: float, y2: float,
) -> List[Tuple[float, float, float, float, float, float]]:
    """
    Convert SVG arc to a list of cubic bezier segments.
    Returns list of (cx1, cy1, cx2, cy2, ex, ey) tuples.
    Based on the SVG spec conversion algorithm.
    """
    if x1 == x2 and y1 == y2:
        return []
    if rx == 0 or ry == 0:
        return [(x1, y1, x2, y2, x2, y2)]

    phi = math.radians(phi_deg)
    cos_phi = math.cos(phi)
    sin_phi = math.sin(phi)

    dx = (x1 - x2) / 2
    dy = (y1 - y2) / 2
    x1p =  cos_phi * dx + sin_phi * dy
    y1p = -sin_phi * dx + cos_phi * dy

    rx, ry = abs(rx), abs(ry)
    lam = (x1p / rx) ** 2 + (y1p / ry) ** 2
    if lam > 1:
        sq = math.sqrt(lam)
        rx *= sq
        ry *= sq

    num = max(0.0, (rx * ry) ** 2 - (rx * y1p) ** 2 - (ry * x1p) ** 2)
    den = (rx * y1p) ** 2 + (ry * x1p) ** 2
    sq = math.sqrt(num / den) if den else 0
    if large_arc == sweep:
        sq = -sq

    cxp =  sq * rx * y1p / ry
    cyp = -sq * ry * x1p / rx
    cx = cos_phi * cxp - sin_phi * cyp + (x1 + x2) / 2
    cy = sin_phi * cxp + cos_phi * cyp + (y1 + y2) / 2

    def _angle(ux, uy, vx, vy) -> float:
        n = math.sqrt(ux * ux + uy * uy) * math.sqrt(vx * vx + vy * vy)
        if n == 0:
            return 0.0
        cos_a = max(-1.0, min(1.0, (ux * vx + uy * vy) / n))
        a = math.acos(cos_a)
        if ux * vy - uy * vx < 0:
            a = -a
        return a

    theta1 = _angle(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry)
    dtheta = _angle(
        (x1p - cxp) / rx, (y1p - cyp) / ry,
        (-x1p - cxp) / rx, (-y1p - cyp) / ry,
    )
    if not sweep and dtheta > 0:
        dtheta -= 2 * math.pi
    elif sweep and dtheta < 0:
        dtheta += 2 * math.pi

    # Split into at most 4 segments of ≤ 90°
    n_segs = max(1, math.ceil(abs(dtheta) / (math.pi / 2)))
    dt = dtheta / n_segs
    alpha = math.sin(dt) * (math.sqrt(4 + 3 * math.tan(dt / 2) ** 2) - 1) / 3

    cubics: List[Tuple[float, float, float, float, float, float]] = []
    t = theta1
    for _ in range(n_segs):
        cos_t1 = math.cos(t)
        sin_t1 = math.sin(t)
        t += dt
        cos_t2 = math.cos(t)
        sin_t2 = math.sin(t)

        # End point
        ex = cos_phi * rx * cos_t2 - sin_phi * ry * sin_t2 + cx
        ey = sin_phi * rx * cos_t2 + cos_phi * ry * sin_t2 + cy

        # Control points
        dx1 = -rx * cos_phi * sin_t1 - ry * sin_phi * cos_t1
        dy1 = -rx * sin_phi * sin_t1 + ry * cos_phi * cos_t1
        dx2 =  rx * cos_phi * sin_t2 + ry * sin_phi * cos_t2
        dy2 =  rx * sin_phi * sin_t2 - ry * cos_phi * cos_t2

        cp1x = cos_phi * rx * cos_t1 - sin_phi * ry * sin_t1 + cx + alpha * dx1
        cp1y = sin_phi * rx * cos_t1 + cos_phi * ry * sin_t1 + cy + alpha * dy1
        cp2x = ex - alpha * dx2
        cp2y = ey - alpha * dy2

        cubics.append((cp1x, cp1y, cp2x, cp2y, ex, ey))

    return cubics


class _SvgPathToSegments:
    """
    Parse an SVG path `d` string and call ``segment_callback`` for each
    segment.  Segments are yielded as:
      ("moveto",  [(x, y)])
      ("lineto",  [(x, y)])
      ("curveto", [(c1x,c1y), (c2x,c2y), (x, y)])   # cubic
      ("qcurveto",[(c1x,c1y), (x, y)])               # quadratic
      ("closepath", [])
    """

    def __init__(self, d: str):
        self._d = d

    def segments(self) -> Generator:  # type: ignore[type-arg]
        tokens = _tokenize(self._d)
        cmd: Optional[str] = None
        x = y = 0.0          # current point
        start_x = start_y = 0.0  # subpath start
        last_c2x = last_c2y = 0.0  # last cubic control (for S)
        last_q1x = last_q1y = 0.0  # last quad control (for T)
        prev_cmd: Optional[str] = None

        try:
            token = next(tokens)
        except StopIteration:
            return

        while True:
            if re.fullmatch(r"[MmLlHhVvCcSsQqTtAaZz]", token):
                cmd = token
                try:
                    token = next(tokens)
                except StopIteration:
                    token = ""

            if cmd is None:
                break

            def _peek_num(t: str) -> bool:
                return bool(re.fullmatch(
                    r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?", t
                ))

            def _read(n: int) -> List[float]:
                nonlocal token
                nums: List[float] = []
                while len(nums) < n:
                    if not _peek_num(token):
                        raise ValueError(f"Expected number, got {token!r}")
                    nums.append(float(token))
                    try:
                        token = next(tokens)
                    except StopIteration:
                        token = ""
                return nums

            # ---- M/m ----
            if cmd in ("M", "m"):
                vals = _read(2)
                if cmd == "m":
                    x += vals[0]; y += vals[1]
                else:
                    x, y = vals[0], vals[1]
                start_x, start_y = x, y
                yield "moveto", [(x, y)]
                # Subsequent coords are implicit lineto
                cmd = "l" if cmd == "m" else "L"
                prev_cmd = "M"
                continue

            # ---- Z/z ----
            elif cmd in ("Z", "z"):
                yield "closepath", []
                x, y = start_x, start_y
                # *** Do NOT read another token here. ***
                # The top-of-loop already consumed the token that follows Z
                # (storing it in `token`).  Reading again shifts the stream,
                # dropping the subpath-start M and causing spurious closepaths.

            # ---- L/l ----
            elif cmd in ("L", "l"):
                vals = _read(2)
                if cmd == "l":
                    x += vals[0]; y += vals[1]
                else:
                    x, y = vals[0], vals[1]
                yield "lineto", [(x, y)]

            # ---- H/h ----
            elif cmd in ("H", "h"):
                vals = _read(1)
                if cmd == "h":
                    x += vals[0]
                else:
                    x = vals[0]
                yield "lineto", [(x, y)]

            # ---- V/v ----
            elif cmd in ("V", "v"):
                vals = _read(1)
                if cmd == "v":
                    y += vals[0]
                else:
                    y = vals[0]
                yield "lineto", [(x, y)]

            # ---- C/c ----
            elif cmd in ("C", "c"):
                vals = _read(6)
                if cmd == "c":
                    c1x = x + vals[0]; c1y = y + vals[1]
                    c2x = x + vals[2]; c2y = y + vals[3]
                    ex  = x + vals[4]; ey  = y + vals[5]
                else:
                    c1x, c1y, c2x, c2y, ex, ey = vals
                last_c2x, last_c2y = c2x, c2y
                x, y = ex, ey
                yield "curveto", [(c1x, c1y), (c2x, c2y), (x, y)]

            # ---- S/s  (smooth cubic) ----
            elif cmd in ("S", "s"):
                vals = _read(4)
                if cmd == "s":
                    c2x = x + vals[0]; c2y = y + vals[1]
                    ex  = x + vals[2]; ey  = y + vals[3]
                else:
                    c2x, c2y, ex, ey = vals
                # Reflect last control point
                if prev_cmd in ("C", "c", "S", "s"):
                    c1x = 2 * x - last_c2x
                    c1y = 2 * y - last_c2y
                else:
                    c1x, c1y = x, y
                last_c2x, last_c2y = c2x, c2y
                x, y = ex, ey
                yield "curveto", [(c1x, c1y), (c2x, c2y), (x, y)]

            # ---- Q/q  (quadratic) ----
            elif cmd in ("Q", "q"):
                vals = _read(4)
                if cmd == "q":
                    c1x = x + vals[0]; c1y = y + vals[1]
                    ex  = x + vals[2]; ey  = y + vals[3]
                else:
                    c1x, c1y, ex, ey = vals
                last_q1x, last_q1y = c1x, c1y
                x, y = ex, ey
                yield "qcurveto", [(c1x, c1y), (x, y)]

            # ---- T/t  (smooth quadratic) ----
            elif cmd in ("T", "t"):
                vals = _read(2)
                if cmd == "t":
                    ex = x + vals[0]; ey = y + vals[1]
                else:
                    ex, ey = vals
                if prev_cmd in ("Q", "q", "T", "t"):
                    c1x = 2 * x - last_q1x
                    c1y = 2 * y - last_q1y
                else:
                    c1x, c1y = x, y
                last_q1x, last_q1y = c1x, c1y
                x, y = ex, ey
                yield "qcurveto", [(c1x, c1y), (x, y)]

            # ---- A/a  (arc -> cubic) ----
            elif cmd in ("A", "a"):
                vals = _read(7)
                if cmd == "a":
                    ex = x + vals[5]; ey = y + vals[6]
                else:
                    ex, ey = vals[5], vals[6]
                cubics = _arc_to_cubics(
                    x, y,
                    vals[0], vals[1],     # rx, ry
                    vals[2],               # x-rotation
                    int(vals[3]), int(vals[4]),  # large-arc, sweep
                    ex, ey,
                )
                for c1x, c1y, c2x, c2y, px, py in cubics:
                    last_c2x, last_c2y = c2x, c2y
                    yield "curveto", [(c1x, c1y), (c2x, c2y), (px, py)]
                x, y = ex, ey

            else:
                # Unrecognised command - skip token
                try:
                    token = next(tokens)
                except StopIteration:
                    break
                prev_cmd = cmd
                continue

            prev_cmd = cmd
            # Check if next token starts a new command or is a repeating coord
            if not token or not _peek_num(token):
                if not token:
                    break
                # It's the next command; don't call next()
            # else: same command repeats with next set of coords


