class _Transform:
    """
    Converts SVG coordinates -> font units.

    Params
    ------
    cap_height  : cap-height in font units (typically 700)
    svg_ref     : SVG artboard height (typically 1000)
    """

    def __init__(self, cap_height: float, svg_ref: float) -> None:
        self.scale = cap_height / svg_ref
        self.cap_height = cap_height

    def pt(self, sx: float, sy: float) -> tuple[float, float]:
        return (
            round(sx * self.scale, 3),
            round(self.cap_height - sy * self.scale, 3),
        )


