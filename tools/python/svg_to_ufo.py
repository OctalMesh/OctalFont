#!/usr/bin/env python3
"""
svg_to_ufo.py - Convert per-glyph SVG files into a UFO master and a
DesignSpace document suitable for fontmake / gftools builder.

Pipeline
--------
  sources/<Family>/svg/**/*.svg
        │
        ▼  (this script)
  sources/<Family>/ufo/<Weight>.ufo/
  sources/<Family>/<Family>.designspace
        │
        ▼  (gftools builder / fontmake)
  fonts/<Family>/…

SVG coordinate assumptions
--------------------------
  • Artboard is a square of side ``svg_ref_size`` (default 1000).
  • Y = 0  ->  top of capital (cap-height in font coords).
  • Y = svg_ref_size -> baseline (y = 0 in font coords).
  • Descenders extending below baseline are expected to have
    Y > svg_ref_size in their SVG artboard.

Coordinate transform
--------------------
  scale  = cap_height / svg_ref_size
  x_font = x_svg * scale
  y_font = cap_height - y_svg * scale

Usage
-----
  python tools/python/svg_to_ufo.py sources/OctalFont-Titan
  python tools/python/svg_to_ufo.py sources/OctalFont-Titan --weight Regular
  python tools/python/svg_to_ufo.py sources/OctalFont-Titan --dry-run
"""

