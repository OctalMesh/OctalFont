def _points_attr_to_path(points_str: str, close: bool) -> str:
    """
    Convert a <polygon>/<polyline> ``points`` attribute value into an SVG
    path ``d`` string so the same parser can handle it.

    ``close=True``  -> polygon  (implicit Z at end)
    ``close=False`` -> polyline (open path)
    """
    # points are whitespace- or comma-separated numbers
    nums = re.split(r"[\s,]+", points_str.strip())
    nums = [n for n in nums if n]  # drop empty strings
    if len(nums) < 4 or len(nums) % 2 != 0:
        return ""  # degenerate – skip
    coords = [float(n) for n in nums]
    pairs = [(coords[i], coords[i + 1]) for i in range(0, len(coords), 2)]
    d = "M {},{}".format(pairs[0][0], pairs[0][1])
    for px, py in pairs[1:]:
        d += " L {},{}".format(px, py)
    if close:
        d += " Z"
    return d


def _load_svg_paths(path: Path) -> tuple[float, list[str]]:
    """
    Parse an SVG file and return (viewbox_width, list_of_path_d_strings).
    Handles <path>, <polygon>, and <polyline> elements.
    Falls back to width attribute if viewBox is absent.
    """
    tree = ET.parse(path)
    root = tree.getroot()

    # Strip namespace prefix if present
    tag = root.tag.replace(f"{{{SVG_NS}}}", "")
    if tag != "svg":
        raise ValueError(f"Root element is not <svg>: {root.tag}")

    viewbox_w = 1000.0
    vb = root.get("viewBox")
    if vb:
        parts = vb.split()
        if len(parts) == 4:
            viewbox_w = float(parts[2])
    elif root.get("width"):
        viewbox_w = float(root.get("width", "1000").rstrip("px"))

    ds: list[str] = []
    for elem in root.iter():
        local = elem.tag.replace(f"{{{SVG_NS}}}", "")

        if local == "path":
            d = elem.get("d", "").strip()
            if d:
                ds.append(d)

        elif local == "polygon":
            pts = elem.get("points", "").strip()
            if pts:
                d = _points_attr_to_path(pts, close=True)
                if d:
                    ds.append(d)

        elif local == "polyline":
            pts = elem.get("points", "").strip()
            if pts:
                # Font glyph outlines are always closed filled shapes.
                # Illustrator may export a closed shape as <polyline> without
                # repeating the first point - close it explicitly.
                d = _points_attr_to_path(pts, close=True)
                if d:
                    ds.append(d)

    return viewbox_w, ds


def _svg_to_glyph(
    svg_path: Path,
    glyph: "ufoLib2.objects.Glyph",
    transform: _Transform,
    advance_width: Optional[float] = None,
) -> None:
    """Parse SVG and draw contours into *glyph* using its point pen."""
    viewbox_w, path_data = _load_svg_paths(svg_path)
    pen = glyph.getPointPen()

    if advance_width is None:
        glyph.width = round(viewbox_w * transform.scale)
    else:
        glyph.width = round(advance_width)

    for d in path_data:
        parser = _SvgPathToSegments(d)

        # ------------------------------------------------------------------
        # Collect sub-path points before emitting, so we know if it's closed
        # PointPen rules:
        #   Closed contour -> no "move" point; first point has a real segmentType
        #   Open contour   -> first point has segmentType="move"
        # ------------------------------------------------------------------
        subpath_pts: list[tuple[float, float, Optional[str]]] = []
        # (x, y, segmentType)  where segmentType=None means off-curve

        closed = False
        start_xy: tuple[float, float] = (0.0, 0.0)

        def _flush(closed_contour: bool) -> None:
            if not subpath_pts:
                return
            pen.beginPath()
            for ix, (px, py, st) in enumerate(subpath_pts):
                if ix == 0 and not closed_contour:
                    pen.addPoint((px, py), segmentType="move")
                else:
                    pen.addPoint((px, py), segmentType=st)
            pen.endPath()

        for seg_type, pts in parser.segments():
            if seg_type == "moveto":
                # flush previous sub-path as open (Z would have already flushed)
                if subpath_pts:
                    _flush(False)
                    subpath_pts = []
                fx, fy = transform.pt(*pts[0])
                start_xy = (fx, fy)
                subpath_pts = [(fx, fy, "line")]   # placeholder; open=move, closed=line
                closed = False

            elif seg_type == "lineto":
                if not subpath_pts:
                    continue
                fx, fy = transform.pt(*pts[0])
                subpath_pts.append((fx, fy, "line"))

            elif seg_type == "curveto":
                if not subpath_pts:
                    continue
                (c1x, c1y), (c2x, c2y), (ex, ey) = [
                    transform.pt(*p) for p in pts
                ]
                subpath_pts.append((c1x, c1y, None))    # off-curve
                subpath_pts.append((c2x, c2y, None))    # off-curve
                subpath_pts.append((ex, ey, "curve"))

            elif seg_type == "qcurveto":
                if not subpath_pts:
                    continue
                (c1x, c1y), (ex, ey) = [transform.pt(*p) for p in pts]
                subpath_pts.append((c1x, c1y, None))
                subpath_pts.append((ex, ey, "qcurve"))

            elif seg_type == "closepath":
                # Remove duplicate closing point if the last point equals start
                if subpath_pts:
                    last = subpath_pts[-1]
                    sx, sy = start_xy
                    if abs(last[0] - sx) < 0.5 and abs(last[1] - sy) < 0.5 and last[2] is not None:
                        subpath_pts.pop()
                _flush(True)
                subpath_pts = []
                closed = True

        # Any remaining open sub-path
        if subpath_pts:
            _flush(False)


