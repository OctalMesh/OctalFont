"""Generate all derived sources (UFOs, designspace, gftools config) from font.yaml."""

from __future__ import annotations

import shutil
from pathlib import Path

import yaml
from fontTools.designspaceLib import (
    AxisDescriptor,
    DesignSpaceDocument,
    InstanceDescriptor,
    SourceDescriptor,
)

from .composites import CompositeConfig, estimate_stack_top
from .config import FontConfig
from .ufobuild import build_master, font_extremes

# GF guide: ascender must equal the height of Abreveacute (U+1EAE)
VIETNAMESE_REFERENCE = (0x0041, [0x0306, 0x0301])  # A + breve + acute


def ufo_path(cfg: FontConfig, style: str) -> Path:
    return cfg.sources / "ufo" / f"{cfg.file_stem}-{style.replace(' ', '')}.ufo"


def write_designspace(cfg: FontConfig) -> Path:
    ds = DesignSpaceDocument()
    weights = sorted(m.weight for m in cfg.masters)
    axis = AxisDescriptor(name="Weight", tag="wght", minimum=weights[0],
                          default=next((w for w in weights if w == 400), weights[0]),
                          maximum=weights[-1])
    axis.labelNames = {"en": "Weight"}

    ds.addAxis(axis)

    for m in cfg.masters:
        src = SourceDescriptor(
            filename=f"ufo/{ufo_path(cfg, m.style).name}", name=f"{cfg.family} {m.style}",
            familyName=cfg.family, styleName=m.style, location={"Weight": m.weight},
        )

        ds.addSource(src)
        ds.addInstance(InstanceDescriptor(
            familyName=cfg.family, styleName=m.style,
            name=f"{cfg.family} {m.style}", location={"Weight": m.weight},
            filename=f"instance_ufos/{cfg.ps_name(m.style)}.ufo",  # required by gftools builder
        ))

    path = cfg.sources / f"{cfg.file_stem}.designspace"

    ds.write(path)

    return path


def write_gftools_config(cfg: FontConfig, designspace: Path) -> Path:
    """gftools-builder config; ``build:`` in font.yaml overrides the defaults."""

    conf: dict = {
        "sources": [designspace.name],
        "familyName": cfg.family,
        "buildVariable": len(cfg.masters) > 1,
        "buildTTF": True,
        "buildOTF": False,
        "buildWebfont": False,
        "cleanUp": True,
        "autohintTTF": False,
    }
    conf.update(cfg.build)

    path = cfg.sources / "config.yaml"
    path.write_text("# Generated by `octalfont sources` from font.yaml. Do not edit.\n"
                    + yaml.safe_dump(conf, sort_keys=False), encoding="utf-8")

    return path


def build_sources(cfg: FontConfig) -> dict:
    from . import glyphnames

    glyphnames.PROJECT_GLYPHSET_DIR = cfg.sources / "glyphsets"

    comp = CompositeConfig.load(cfg.sources / cfg.composites_file)
    ufos, reports, warnings = {}, {}, []

    for m in cfg.masters:
        ufo, rep, warn = build_master(cfg, m, comp)
        ufos[m.style], reports[m.style] = ufo, rep
        warnings += warn

    ymax, ymin = font_extremes(ufos.values())

    for ufo in ufos.values():
        ufo.info.openTypeOS2WinAscent = max(ymax, ufo.info.ascender)
        ufo.info.openTypeOS2WinDescent = abs(min(ymin, ufo.info.descender))

    for m in cfg.masters:
        path = ufo_path(cfg, m.style)

        if path.exists():
            shutil.rmtree(path)

        path.parent.mkdir(parents=True, exist_ok=True)
        ufos[m.style].save(path, overwrite=True)

    ds = write_designspace(cfg)
    gf = write_gftools_config(cfg, ds)

    return {"ufos": ufos, "reports": reports, "warnings": warnings,
            "designspace": ds, "config": gf, "win": (ymax, ymin), "composites": comp}


def vietnamese_estimate(ufo, comp: CompositeConfig) -> float | None:
    base_cp, marks = VIETNAMESE_REFERENCE
    cmap = {u: g.name for g in ufo for u in g.unicodes}

    if base_cp not in cmap:
        return None

    return estimate_stack_top(ufo, comp, cmap[base_cp], marks)
